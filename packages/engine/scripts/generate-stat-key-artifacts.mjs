#!/usr/bin/env node
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const engineRoot = resolve(__dirname, "..");
const contractsDataDir = join(
  engineRoot,
  "src",
  "escape-the-dungeon",
  "contracts",
  "data"
);
const generatedTsPath = join(
  engineRoot,
  "src",
  "escape-the-dungeon",
  "contracts",
  "generated",
  "stat-keys.ts"
);
const generatedPyDir = join(resolve(engineRoot, "..", ".."), "notebooks", "generated");
const generatedPyPath = join(generatedPyDir, "stat_keys.py");
const generatedEntityModelPyPath = join(generatedPyDir, "entity_model.py");

const readJson = (filePath) => JSON.parse(readFileSync(filePath, "utf8"));

const writeText = (filePath, value) => {
  mkdirSync(dirname(filePath), { recursive: true });
  writeFileSync(filePath, value, "utf8");
};

const assertArray = (value, label) => {
  if (!Array.isArray(value)) {
    throw new Error(`${label} must be an array.`);
  }
  return value;
};

const combatPack = readJson(join(contractsDataDir, "lookup_combat_stats.json"));
const skillPack = readJson(join(contractsDataDir, "lookup_skill_stats.json"));
const narrativePack = readJson(join(contractsDataDir, "lookup_narrative_traits.json"));
const runePack = readJson(join(contractsDataDir, "lookup_runes.json"));

const combatRows = assertArray(combatPack.stats, "lookup_combat_stats.stats");
const skillRows = assertArray(skillPack.stats, "lookup_skill_stats.stats");
const narrativeRows = assertArray(narrativePack.traits, "lookup_narrative_traits.traits");
const runeRows = assertArray(runePack.runes, "lookup_runes.runes");

const uniqueStrings = (values) => [...new Set(values.map((value) => String(value)).filter(Boolean))];

const combatStatIds = uniqueStrings(combatRows.map((row) => row.statId));
const combatStatKeys = uniqueStrings(combatRows.map((row) => row.entityKey));
const combatStatIdToKey = Object.fromEntries(
  combatRows.map((row) => [String(row.statId), String(row.entityKey)])
);
const combatStatDefaults = Object.fromEntries(
  combatRows.map((row) => [String(row.entityKey), Number(row.defaultValue ?? 0)])
);

const skillStatIds = uniqueStrings(skillRows.map((row) => row.statId));
const skillStatKeys = uniqueStrings(skillRows.map((row) => row.entityKey));
const skillStatIdToKey = Object.fromEntries(
  skillRows.map((row) => [String(row.statId), String(row.entityKey)])
);
const skillStatDefaults = Object.fromEntries(
  skillRows.map((row) => [String(row.entityKey), Number(row.defaultValue ?? 0)])
);

const narrativeStatIds = uniqueStrings(narrativeRows.map((row) => row.traitId));
const narrativeStatNames = uniqueStrings(
  narrativeRows.map((row) => row.entityKey ?? row.name)
);
const narrativeStatIdToKey = Object.fromEntries(
  narrativeRows.map((row) => [String(row.traitId), String(row.entityKey ?? row.name)])
);
const narrativeStatDefaults = Object.fromEntries(
  narrativeRows.map((row) => [String(row.entityKey ?? row.name), Number(row.defaultValue ?? 0)])
);

const runeIds = uniqueStrings(runeRows.map((row) => row.runeId));

const toTsLiteral = (value) => `${JSON.stringify(value, null, 2)} as const`;

writeText(
  generatedTsPath,
  `// generated by scripts/generate-stat-key-artifacts.mjs\n` +
    `export const COMBAT_STAT_IDS = ${toTsLiteral(combatStatIds)};\n` +
    `export const COMBAT_STAT_KEYS = ${toTsLiteral(combatStatKeys)};\n` +
    `export const COMBAT_STAT_ID_TO_KEY = ${toTsLiteral(combatStatIdToKey)};\n` +
    `export const COMBAT_STAT_DEFAULTS = ${toTsLiteral(combatStatDefaults)};\n\n` +
    `export const SKILL_STAT_IDS = ${toTsLiteral(skillStatIds)};\n` +
    `export const SKILL_STAT_KEYS = ${toTsLiteral(skillStatKeys)};\n` +
    `export const SKILL_STAT_ID_TO_KEY = ${toTsLiteral(skillStatIdToKey)};\n` +
    `export const SKILL_STAT_DEFAULTS = ${toTsLiteral(skillStatDefaults)};\n\n` +
    `export const NARRATIVE_STAT_IDS = ${toTsLiteral(narrativeStatIds)};\n` +
    `export const NARRATIVE_STAT_NAMES = ${toTsLiteral(narrativeStatNames)};\n` +
    `export const NARRATIVE_STAT_ID_TO_KEY = ${toTsLiteral(narrativeStatIdToKey)};\n` +
    `export const NARRATIVE_STAT_DEFAULTS = ${toTsLiteral(narrativeStatDefaults)};\n\n` +
    `export const RUNE_IDS = ${toTsLiteral(runeIds)};\n`
);

writeText(
  generatedPyPath,
  `# generated by packages/engine/scripts/generate-stat-key-artifacts.mjs\n` +
    `COMBAT_STAT_IDS = ${JSON.stringify(combatStatIds, null, 2)}\n` +
    `COMBAT_STAT_KEYS = ${JSON.stringify(combatStatKeys, null, 2)}\n` +
    `COMBAT_STAT_ID_TO_KEY = ${JSON.stringify(combatStatIdToKey, null, 2)}\n` +
    `COMBAT_STAT_DEFAULTS = ${JSON.stringify(combatStatDefaults, null, 2)}\n\n` +
    `SKILL_STAT_IDS = ${JSON.stringify(skillStatIds, null, 2)}\n` +
    `SKILL_STAT_KEYS = ${JSON.stringify(skillStatKeys, null, 2)}\n` +
    `SKILL_STAT_ID_TO_KEY = ${JSON.stringify(skillStatIdToKey, null, 2)}\n` +
    `SKILL_STAT_DEFAULTS = ${JSON.stringify(skillStatDefaults, null, 2)}\n\n` +
    `NARRATIVE_STAT_IDS = ${JSON.stringify(narrativeStatIds, null, 2)}\n` +
    `NARRATIVE_STAT_NAMES = ${JSON.stringify(narrativeStatNames, null, 2)}\n` +
    `NARRATIVE_STAT_ID_TO_KEY = ${JSON.stringify(narrativeStatIdToKey, null, 2)}\n` +
    `NARRATIVE_STAT_DEFAULTS = ${JSON.stringify(narrativeStatDefaults, null, 2)}\n\n` +
    `RUNE_IDS = ${JSON.stringify(runeIds, null, 2)}\n`
);

writeText(
  generatedEntityModelPyPath,
  `# generated by packages/engine/scripts/generate-stat-key-artifacts.mjs\n` +
    `from pydantic import BaseModel, Field\n\n` +
    `class EntityModel(BaseModel):\n` +
    `    entity_id: str\n` +
    `    name: str = ""\n` +
    `    combat_stats: dict[str, float] = Field(default_factory=dict)\n` +
    `    skill_stats: dict[str, float] = Field(default_factory=dict)\n` +
    `    narrative_stats: dict[str, float] = Field(default_factory=dict)\n` +
    `    rune_stats: dict[str, float] = Field(default_factory=dict)\n`
);

console.log(`[stat-keys] wrote ${generatedTsPath}`);
console.log(`[stat-keys] wrote ${generatedPyPath}`);
console.log(`[stat-keys] wrote ${generatedEntityModelPyPath}`);
